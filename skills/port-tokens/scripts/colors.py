"""Bring Figma's Colors page in line with the colour variables, after a port or any value change.

  python3 -I colors.py prepare [--root DIR]     writes .sync/colors-read.js; run it with use_figma (it only reads)
  python3 -I colors.py plan [--root DIR]        the dry run; saves .sync/colors-plan.json
  python3 -I colors.py write [--root DIR] [--skip ID ...] [--keep-colour ID ...] [--approve-family NAME ...]
                                                writes .sync/colors-write.js from the plan; run it
  python3 -I colors.py finish [--root DIR]      reports what Figma accepted

What it keeps true, page-wide (every swatch, not only what this run changed, so drift from hand edits is caught too):
  - each swatch's name, and its second slot: the hex for a primitive, the aliased primitive's name for a semantic token;
  - the four contrast verdicts: 16pt is small text (4.5:1), 24pt large text (3:1), each for black and for white text;
  - the Text Color variant: whichever of black or white labels reads better on the swatch;
  - the Color Scales ramps, regenerated by scales.py when a family's anchor or members moved;
  - a swatch for every colour variable, and for a new colour family a palette row and a scale.
Names follow the page's own convention, inferred from the swatches that already agree with their variable.
"""
import argparse
import json
import re
import secrets
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent.parent / "ds-sync" / "scripts"))
import synclib as L
from figma_read import find_result
from scales import ramp, hsl, STEPS, TOP, BOT

TRANSFORMS = {
    "leafTitle": lambda n: "-".join(w[:1].upper() + w[1:] for w in n.split("/")[-1].split("-")),
    "leaf": lambda n: n.split("/")[-1],
    "full": lambda n: n,
    "fullSpaced": lambda n: " / ".join(n.split("/")),
}


def lum(h):
    f = lambda x: x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def ratio(a, b):
    hi, lo = sorted([lum(a), lum(b)], reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def tag_path(root):
    return root / ".sync" / "colors-tag.json"


def prepare(root):
    (root / ".sync" / "figma-colors.json").unlink(missing_ok=True)
    nonce = secrets.token_hex(6)
    js = (HERE / "colors.template.js").read_text().replace("__INPUT__", json.dumps({"mode": "read", "nonce": nonce, "exclude": L.load_config(root).get("exclude") or []}))
    (root / ".sync" / "colors-read.js").write_text(js)
    tag_path(root).write_text(json.dumps({"read": nonce}) + "\n")
    print(f"Wrote .sync/colors-read.js ({len(js) // 1024} KB). Run it with use_figma for file {L.load_config(root)['figma']['file_key']}, then run `colors.py plan`.")


def plan(root):
    got = find_result(root, "colors", json.loads(tag_path(root).read_text())["read"])
    V, keys = got["vars"], got["keys"]
    key = lambda pat: next((k for k in keys if re.search(pat, k, re.I)), None)
    K = {"name": key(r"^color name"), "hex": key(r"^hex"), "colour": key(r"^text colou?r")}
    VK = {(size, ink): key(rf"^{size}pt {ink}") for size in ("16", "24") for ink in ("Black", "White")}     # the four verdicts
    props = lambda s: dict(zip(keys, s["p"]))
    solid = lambda n: n in V and V[n]["h"] and (V[n]["a"] or 0) >= 0.999
    ops, notes, report = [], [], {"renames": [], "permissive": [], "strict": [], "hex": [], "colour_unreadable": [], "colour_better": []}

    # the page's naming convention, per board, from swatches whose label already matches their variable
    tally = Counter()
    for s in got["swatches"]:
        if s["v"]:
            for t, f in TRANSFORMS.items():
                if props(s).get(K["name"]) == f(s["v"]):
                    tally[(s["b"], t)] += 1
    convention = {}
    for b in {s["b"] for s in got["swatches"]}:
        best = max(TRANSFORMS, key=lambda t: tally[(b, t)])
        convention[b] = best if tally[(b, best)] else None
    hexes = [props(s).get(K["hex"]) for s in got["swatches"] if re.fullmatch(r"#?[0-9A-Fa-f]{6}", str(props(s).get(K["hex"])))]
    lettered = [h for h in hexes if re.search(r"[A-Fa-f]", h)]
    upper = not lettered or sum(h == h.upper() for h in lettered) >= len(lettered) / 2
    hashed = not hexes or sum(h.startswith("#") for h in hexes) >= len(hexes) / 2
    fmt = lambda h: ("#" if hashed else "") + (h.lstrip("#").upper() if upper else h.lstrip("#").lower())

    def want_props(name, board, current=None):
        """Every property a swatch for this variable should show. current: its present values, for the label-colour rule."""
        tf = TRANSFORMS[convention.get(board) or "leafTitle"]
        h = V[name]["h"]
        vb, vw = ratio(h, "#000000"), ratio(h, "#ffffff")
        out = {K["name"]: tf(name), K["hex"]: tf(V[name]["al"]) if V[name]["al"] else fmt(h)}
        for (size, ink), k in VK.items():
            if k:
                out[k] = "Pass" if (vb if ink == "Black" else vw) >= (4.5 if size == "16" else 3) else "Fail"
        best = "Black" if vb >= vw else "White"
        near = max(vb, vw) / min(vb, vw) < 1.15
        out[K["colour"]] = current if (near and current) else best
        return out, vb, vw

    # the label-colour rule only applies if most swatches already follow it
    agree = sum(1 for s in got["swatches"] if solid(s["v"]) and want_props(s["v"], s["b"], props(s).get(K["colour"]))[0][K["colour"]] == props(s).get(K["colour"]))
    colour_rule = agree >= len([s for s in got["swatches"] if solid(s["v"])]) / 2
    if not colour_rule:
        notes.append("Most swatches don't use the more readable label colour, so label colour is left as it is.")

    checked = agreed = 0
    for s in got["swatches"]:
        if not s["v"]:
            notes.append(f"Swatch `{s['id']}` isn't bound to a variable, so it can't be checked.")
            continue
        if not solid(s["v"]):
            a = (V.get(s["v"]) or {}).get("a") or 0
            m = re.search(r"(\d+)\s*%", str(props(s).get(K["hex"])))
            drift = f" Its label says {m.group(1)}%, but the variable is {round(a * 100)}%." if m and int(m.group(1)) != round(a * 100) else ""
            notes.append(f"`{s['v']}` is translucent ({round(a * 100)}% opacity), so its contrast can't be judged on its own; its swatch is left as it is.{drift}")
            continue
        checked += 1
        cur = props(s)
        want, vb, vw = want_props(s["v"], s["b"], cur.get(K["colour"]))
        if not colour_rule:
            want[K["colour"]] = cur.get(K["colour"])
        diff = {k: v for k, v in want.items() if k and cur.get(k) != v}
        if not diff:
            agreed += 1
            continue
        ops.append({"t": "props", "id": s["id"], "props": diff, "var": s["v"]})
        label = f"`{s['v']}` ({V[s['v']]['h']}; {vb:.2f}:1 with black, {vw:.2f}:1 with white)"
        if K["name"] in diff:
            report["renames"].append(f"{label}: “{cur.get(K['name'])}” → “{diff[K['name']]}”")
        if K["hex"] in diff:
            report["hex"].append(f"{label}: {cur.get(K['hex'])} → {diff[K['hex']]}")
        for (size, ink), k in VK.items():
            if k in diff:
                line = f"{label}: {size}pt {ink.lower()} text {cur.get(k)} → {diff[k]}"
                report["permissive" if cur.get(k) == "Pass" else "strict"].append(line)
        if K["colour"] in diff:
            now = vb if cur.get(K["colour"]) == "Black" else vw
            report["colour_unreadable" if now < 3 else "colour_better"].append(f"{label}: {cur.get(K['colour'])} labels → {diff[K['colour']]}")

    # ── Color Scales ──
    family_of = lambda anchor: anchor.rsplit("-", 1)[0] + "-"
    scale_ops = []
    for f in got["scales"]:
        a = f["anchor"]
        if not a or not solid(a):
            notes.append(f"Color Scales › {f['name']}: its anchor swatch isn't bound to a solid colour; left alone.")
            continue
        members = [V[n]["h"] for n in V if n.startswith(family_of(a)) and solid(n)]
        try:
            new, pins = ramp(f["name"], V[a]["h"], members)
        except ValueError as e:
            notes.append(f"Color Scales › {e}. Nothing written for it.")
            continue
        current = ["#" + h.lstrip("#").upper() for _, h, _ in f["steps"]]
        if f["frameName"].upper() == V[a]["h"].upper() and current == new:
            continue
        # calibrate: is the current ramp this generator's work? step 5 is the frame's hex and the ends sit at 95/18
        Ls = [hsl(h)[2] for h in current]
        if current and current[0] == "#FFFFFF" and current[-1] == "#000000":
            kind, ok = "the earlier white-to-black generator", False
        elif current and current[7] == f["frameName"].upper() and abs(Ls[0] - TOP) < 1.5 and abs(Ls[-1] - BOT) < 1.5 + (10 if f["name"].lower() == "yellow" else 0) \
                and all(x > y for x, y in zip(Ls, Ls[1:])):
            kind, ok = "these rules", True
        else:
            kind, ok = None, False
        if kind is None:
            notes.append(f"Color Scales › {f['name']}: the ramp doesn't follow these rules (another tool, or edited by hand). Left alone.")
            continue
        bound = [st for st, _, b in f["steps"] if b]
        if bound:
            notes.append(f"Color Scales › {f['name']}: steps {', '.join(bound)} have a fill bound to a variable; they're left alone.")
        scale_ops.append({"t": "ramp", "frame": f["frame"], "name": V[a]["h"].upper(), "steps": new, "family": f["name"], "needs_ok": not ok,
                          "pins": {n: pins.get(V[n]["h"].lower()) for n in V if n.startswith(family_of(a)) and solid(n) and n != a}, "was": f["frameName"]})
    ops += scale_ops

    # ── a swatch for every colour variable ──
    on_page = {s["v"] for s in got["swatches"]}
    order = list(V)
    rows = got["rows"]
    group = lambda n: n.split("/")[0]
    new_rows = {}
    added = []
    for n in order:
        if n in on_page:
            continue
        home = [r for r in rows if any(v and group(v) == group(n) for v in r["vars"])]
        if home:
            r = home[0]
            before = [v for v in order[:order.index(n)] if v in r["vars"] or any(a["var"] == v for a in added if a["ct"] == r["ct"])]
            after_var = before[-1] if before else None
            after = next((s["id"] for s in got["swatches"] if s["v"] == after_var and s["ct"] == r["ct"]), None)
            spec = {"t": "swatch", "ct": r["ct"], "after": after, "var": n, "row": r["title"]}
            if not after and after_var:
                spec["after_var"] = after_var
            added.append(spec)
        else:
            new_rows.setdefault(group(n), []).append(n)
    for spec in added:
        if not solid(spec["var"]):
            notes.append(f"`{spec['var']}` has no swatch, but it's translucent; add one by hand if it needs documenting.")
            continue
        p, _, _ = want_props(spec["var"], next((r["b"] for r in rows if r["ct"] == spec["ct"]), None))
        spec["variant"], spec["props"] = p.pop(K["colour"]), p
        ops.append(spec)
    for g, names in new_rows.items():
        coll = V[names[0]]["c"]
        same = [r for r in rows if r["vars"] and all(v and V.get(v, {}).get("c") == coll for v in r["vars"] if v)]
        if not same:
            notes.append(f"`{g}/…` has no swatches and no row of its collection to copy; add its row by hand.")
            continue
        src = same[-1]
        title = g.replace("-", " ").title() + (" Palette" if src["title"].endswith("Palette") else "")
        swatches = []
        for n in names:
            if not solid(n):
                continue
            p, _, _ = want_props(n, src["b"])
            swatches.append({"var": n, "variant": p.pop(K["colour"]), "props": p})
        ops.append({"t": "row", "clone": src["id"], "name": title, "title": title, "desc": f"Describe when to use the {g.replace('-', ' ')} palette.", "swatches": swatches, "after_row": src["title"]})
        # and its scale, anchored like the others (the -300 step, say)
        if got["scales"]:
            suffix = Counter(s["anchor"].rsplit("-", 1)[-1] for s in got["scales"] if s["anchor"]).most_common(1)[0][0]
            anchor = next((n for n in names if n.endswith("-" + suffix) and solid(n)), None)
            if anchor:
                fam = g.replace("-", " ").title()
                try:
                    steps, pins = ramp(fam, V[anchor]["h"], [V[n]["h"] for n in names if solid(n)])
                    p, _, _ = want_props(anchor, got["scales"][-1].get("b"))
                    ops.append({"t": "family", "clone": got["scales"][-1]["id"], "name": fam, "anchor": anchor, "props": {**p}, "rampName": V[anchor]["h"].upper(),
                                "steps": steps, "pins": {n: pins.get(V[n]["h"].lower()) for n in names if n != anchor}})
                except ValueError as e:
                    notes.append(f"Color Scales › {e}. No scale added for {g}.")

    (root / ".sync" / "colors-plan.json").write_text(json.dumps({"ops": ops, "variants": got["variants"], "notes": notes}, indent=1, ensure_ascii=False) + "\n")
    out = [f"Colors page: {len(got['swatches'])} swatches, {checked} checked, {agreed} already right. "
           f"Naming convention: {', '.join(f'{b}: {t}' for b, t in convention.items() if t)} "
           f"({sum(tally[(b, t)] for b, t in convention.items() if t)} swatches agree)."]
    if report["permissive"]:
        out += ["", f"## Verdicts that say Pass but fail ({len(report['permissive'])}): wrong in the harmful direction"] + [f"- {l}" for l in report["permissive"]]
    if report["strict"]:
        out += ["", f"## Verdicts that say Fail but pass ({len(report['strict'])})"] + [f"- {l}" for l in report["strict"]]
    if report["renames"]:
        out += ["", f"## Renamed tokens ({len(report['renames'])})"] + [f"- {l}" for l in report["renames"]]
    if report["hex"]:
        out += ["", f"## Hex or alias labels ({len(report['hex'])})"] + [f"- {l}" for l in report["hex"]]
    if report["colour_unreadable"]:
        out += ["", f"## Label colour, unreadable now ({len(report['colour_unreadable'])})"] + [f"- {l}" for l in report["colour_unreadable"]]
    if report["colour_better"]:
        out += ["", f"## Label colour, readable but the other is better ({len(report['colour_better'])}): keep any with --keep-colour ID"] + [f"- {l}" for l in report["colour_better"]]
    for o in scale_ops:
        if o["family"].lower() == "neutral":      # one hue, never pinned: say where each gray lands instead
            Ls = list(zip(STEPS, (hsl(h)[2] for h in o["steps"])))
            land = lambda h: min(Ls, key=lambda x: abs(x[1] - hsl(h)[2]))
            pins = "none, by design. Where the grays land: " + ", ".join(
                f"`{n}` step {land(V[n]['h'])[0]:g} ({hsl(V[n]['h'])[2] - land(V[n]['h'])[1]:+.1f})" for n in o["pins"])
        else:
            pins = ", ".join(f"`{n}` → step {p:g}" if p is not None else f"`{n}` → outside the ramp's range, not pinned" for n, p in o["pins"].items())
        out += ["", f"## Color Scales › {o['family']}: regenerate ({o['was']} → {o['name']})" + (" — made by an earlier generator; written only with --approve-family " + o["family"] if o["needs_ok"] else ""),
                " ".join(o["steps"]), f"Pins: {pins or 'none (single hue)'}"]
    adds = [o for o in ops if o["t"] in ("swatch", "row", "family")]
    if adds:
        out += ["", f"## New ({len(adds)})"]
        for o in adds:
            if o["t"] == "swatch":
                out.append(f"- Swatch for `{o['var']}` in {o['row']}" + (f", after `{o.get('after_var')}`" if o.get("after_var") else ""))
            elif o["t"] == "row":
                out.append(f"- Row “{o['title']}” after {o['after_row']}, with {', '.join('`' + s['var'] + '`' for s in o['swatches'])}. Its description needs writing.")
            else:
                out.append(f"- Scale “{o['name']}” anchored on `{o['anchor']}`: {' '.join(o['steps'])}")
                if 40 <= hsl(V[o["anchor"]]["h"])[0] <= 65:
                    out.append(f"  {o['name']} is a yellow. Yellow's own scale spaces its dark half by perceived lightness; say if {o['name']} should too.")
    if notes:
        out += ["", "## Left alone"] + [f"- {n}" for n in notes]
    print("\n".join(out))


def write(root, skip, keep_colour, families):
    p = json.loads((root / ".sync" / "colors-plan.json").read_text())
    ops = []
    for o in p["ops"]:
        if o.get("id") in skip or o.get("var") in skip or (o["t"] == "ramp" and o["needs_ok"] and o["family"] not in families):
            continue
        if o["t"] == "props" and o["id"] in keep_colour:
            o = {**o, "props": {k: v for k, v in o["props"].items() if not re.match(r"text colou?r", k, re.I)}}
        ops.append(o)
    (root / ".sync" / "figma-colors.json").unlink(missing_ok=True)
    nonce = secrets.token_hex(6)
    clean = [{k: v for k, v in o.items() if k not in ("pins", "was", "needs_ok", "family", "row", "after_row", "after_var")} for o in ops]
    js = (HERE / "colors.template.js").read_text().replace("__INPUT__", json.dumps({"mode": "write", "nonce": nonce, "ops": clean, "variants": p["variants"],
                                                                                     "exclude": L.load_config(root).get("exclude") or []}, ensure_ascii=False))
    (root / ".sync" / "colors-write.js").write_text(js)
    tag = json.loads(tag_path(root).read_text())
    tag["write"] = nonce
    tag_path(root).write_text(json.dumps(tag) + "\n")
    print(f"Wrote .sync/colors-write.js: {len(ops)} change(s). Run it with use_figma, then run `colors.py finish`.")


def finish(root):
    got = find_result(root, "colors", json.loads(tag_path(root).read_text())["write"])
    print(f"Figma accepted {len(got['done'])} change(s).")
    if got["errors"]:
        print("Refused or left alone:\n" + "\n".join(f"- {e['what']}: {e['error']}" for e in got["errors"]))
    for f in ("colors-read.js", "colors-write.js", "colors-tag.json", "colors-plan.json", "figma-colors.json"):
        (root / ".sync" / f).unlink(missing_ok=True)
    print("Run `colors.py prepare` and the read again: the plan should come back with nothing to do.")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["prepare", "plan", "write", "finish"])
    ap.add_argument("--root")
    ap.add_argument("--skip", nargs="*", default=[], help="swatch ids or variable names the designer struck")
    ap.add_argument("--keep-colour", nargs="*", default=[], help="swatches whose label colour stays as it is")
    ap.add_argument("--approve-family", nargs="*", default=[], help="scales made by an earlier generator that may be regenerated")
    a = ap.parse_args()
    root = L.find_root(a.root)
    {"prepare": lambda: prepare(root), "plan": lambda: plan(root),
     "write": lambda: write(root, set(a.skip), set(a.keep_colour), set(a.approve_family)), "finish": lambda: finish(root)}[a.command]()


if __name__ == "__main__":
    main()
